//! Safety engine for the autofixers (port of
//! `src/autofixers/safety.py`).
//!
//! This is the highest-stakes module in the retirement: it decides
//! which files the fixers may rewrite and which changes escalate to
//! requiring human approval. Every pattern list, every ordering of the
//! checks, and every escalation rule is preserved verbatim — including
//! the ones a redesign would question (see the notes on
//! `assess_risk` and `validate_changes`).

use std::fs::File;
use std::io::{BufReader, Read};
use std::path::Path;

use regex::Regex;

use super::pystr;

/// Risk levels for autofix operations. String values match the Python
/// `Enum` values (they reach stdout and the PR body).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum RiskLevel {
    Low,
    Medium,
    High,
}

impl RiskLevel {
    pub fn as_str(self) -> &'static str {
        match self {
            RiskLevel::Low => "low",
            RiskLevel::Medium => "medium",
            RiskLevel::High => "high",
        }
    }
}

/// Statistics about a proposed content change (Python `ValidationStats`).
/// The counts are CHARACTER deltas — `size_change_bytes` is named for
/// bytes but computed with `len(str)`, so the name is preserved and the
/// arithmetic is code points.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ValidationStats {
    pub original_lines: i64,
    pub new_lines: i64,
    pub lines_added: i64,
    pub size_change_bytes: i64,
}

/// Validation output for a proposed change (Python `ValidationResult`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ValidationResult {
    pub safe: bool,
    pub warnings: Vec<String>,
    pub stats: ValidationStats,
}

