fn compile_all(patterns: &[&str]) -> Vec<Regex> {
    patterns
        .iter()
        .map(|p| Regex::new(&format!("(?i){p}")).expect("static safety pattern must compile"))
        .collect()
}

/// Detect generated files that must not be modified.
pub struct GeneratedFileDetector {
    compiled_patterns: Vec<Regex>,
    compiled_headers: Vec<Regex>,
    build_dirs: Vec<&'static str>,
}

impl Default for GeneratedFileDetector {
    fn default() -> Self {
        Self::new()
    }
}

impl GeneratedFileDetector {
    pub fn new() -> Self {
        GeneratedFileDetector {
            compiled_patterns: compile_all(&GENERATED_PATTERNS),
            compiled_headers: compile_all(&GENERATED_HEADERS),
            build_dirs: BUILD_DIRS.to_vec(),
        }
    }

    /// Port of `is_generated`, check order preserved: lock-file name,
    /// build-directory component, path pattern, then — only for paths
    /// that exist as files — the first ten lines' header markers.
    pub fn is_generated(&self, file_path: &Path) -> bool {
        let file_str = pystr::as_posix(file_path);

        if LOCK_FILES.contains(&pystr::file_name(file_path).as_str()) {
            return true;
        }
        let parts = pystr::named_parts(file_path);
        if self
            .build_dirs
            .iter()
            .any(|dir| parts.iter().any(|part| part == dir))
        {
            return true;
        }
        if self
            .compiled_patterns
            .iter()
            .any(|pattern| pattern.is_match(&file_str))
        {
            return true;
        }

        if file_path.is_file() {
            // `except Exception` in the Python: an unreadable header is
            // logged and treated as "not generated".
            if let Some(header) = read_header_lines(file_path, 10)
                && self
                    .compiled_headers
                    .iter()
                    .any(|pattern| pattern.is_match(&header))
            {
                return true;
            }
        }

        false
    }

    /// Port of `get_safe_files`.
    pub fn get_safe_files<'a>(&self, files: &'a [std::path::PathBuf]) -> Vec<&'a std::path::PathBuf> {
        files
            .iter()
            .filter(|path| !self.is_generated(path))
            .collect()
    }
}

/// `"".join(handle.readline() for _ in range(10))` over a file opened
/// with `encoding="utf-8", errors="ignore"`. Line boundaries are found
/// on the raw bytes first (every terminator is ASCII, and dropped
/// invalid bytes are never `\n`/`\r`), so only the needed prefix is
/// read; the prefix is then decoded with the dropping error handler and
/// newline-translated the way text mode does.
fn read_header_lines(path: &Path, max_lines: usize) -> Option<String> {
    let file = File::open(path).ok()?;
    let mut reader = BufReader::new(file);
    let mut buf: Vec<u8> = Vec::new();
    let mut chunk = [0u8; 4096];
    let mut lines = 0usize;
    let mut scanned = 0usize;
    loop {
        // Count terminators in the bytes we already hold.
        while scanned < buf.len() && lines < max_lines {
            match buf[scanned] {
                b'\n' => {
                    scanned += 1;
                    lines += 1;
                }
                b'\r' => {
                    // `\r\n` is one terminator; a lone `\r` at the very
                    // end of the buffer may still be joined by a `\n`
                    // that has not been read yet.
                    if scanned + 1 < buf.len() {
                        scanned += if buf[scanned + 1] == b'\n' { 2 } else { 1 };
                        lines += 1;
                    } else {
                        break;
                    }
                }
                _ => scanned += 1,
            }
        }
        if lines >= max_lines {
            buf.truncate(scanned);
            break;
        }
        let read = reader.read(&mut chunk).ok()?;
        if read == 0 {
            // EOF: a trailing lone `\r` closes its line.
            break;
        }
        buf.extend_from_slice(&chunk[..read]);
    }
    Some(pystr::translate_newlines(&pystr::decode_utf8_ignore(&buf)))
}

/// Assess risk and validate autofix changes.
pub struct SafetyEngine {
    pub detector: GeneratedFileDetector,
    high_risk: Vec<Regex>,
    medium_risk: Vec<Regex>,
    important_patterns: Vec<(Regex, &'static str)>,
}

impl Default for SafetyEngine {
    fn default() -> Self {
        Self::new()
    }
}

impl SafetyEngine {
    pub fn new() -> Self {
        SafetyEngine {
            detector: GeneratedFileDetector::new(),
            high_risk: compile_all(&HIGH_RISK_PATTERNS),
            medium_risk: compile_all(&MEDIUM_RISK_PATTERNS),
            important_patterns: vec![
                (Regex::new(r"@[a-zA-Z]+\(").unwrap(), "decorators"),
                (Regex::new(r"def\s+\w+").unwrap(), "function definitions"),
                (Regex::new(r"class\s+\w+").unwrap(), "class definitions"),
                (
                    Regex::new(r"export\s+(default\s+)?(class|function|const)").unwrap(),
                    "exports",
                ),
            ],
        }
    }

    /// Port of `assess_risk`. Returns `Err` where the Python raises
    /// `ValueError` (generated file), which `PatchGenerator` turns into
    /// a dropped patch.
    ///
    /// The risk patterns are matched against the FULL path as posix,
    /// not the repo-relative one — so a repository living under a
    /// directory named e.g. `api` escalates every file to medium. That
    /// is the shipped behavior; parity first.
    pub fn assess_risk(&self, file_path: &Path, fix_type: &str) -> Result<RiskLevel, String> {
        let file_str = pystr::as_posix(file_path);

        if self.detector.is_generated(file_path) {
            return Err(format!(
                "Cannot modify generated file: {}",
                file_path.display()
            ));
        }
        if self.high_risk.iter().any(|p| p.is_match(&file_str)) {
            return Ok(RiskLevel::High);
        }
        if self.medium_risk.iter().any(|p| p.is_match(&file_str)) {
            return Ok(RiskLevel::Medium);
        }

        Ok(match fix_type {
            "docs_regen" => RiskLevel::Low,
            "link_fix" => RiskLevel::Low,
            "selector_insert" => RiskLevel::Medium,
            "i18n_scaffold" => RiskLevel::Medium,
            "format_fix" => RiskLevel::Low,
            _ => RiskLevel::Medium,
        })
    }

    /// Port of `validate_changes`.
    ///
    /// Two quirks are load-bearing and preserved: the doubling check is
    /// `len(new) > len(original) * 2`, so ANY non-empty content written
    /// over an empty original trips it (this is what makes every newly
    /// created `FOLDER.md` escalate from low to medium); and the
    /// "reduced X" warnings are informational only — they never clear
    /// `safe`.
    pub fn validate_changes(&self, original_content: &str, new_content: &str) -> ValidationResult {
        let orig_lines = pystr::splitlines(original_content, false);
        let new_lines = pystr::splitlines(new_content, false);
        let orig_len = pystr::char_len(original_content) as i64;
        let new_len = pystr::char_len(new_content) as i64;

        let mut result = ValidationResult {
            safe: true,
            warnings: Vec::new(),
            stats: ValidationStats {
                original_lines: orig_lines.len() as i64,
                new_lines: new_lines.len() as i64,
                lines_added: new_lines.len() as i64 - orig_lines.len() as i64,
                size_change_bytes: new_len - orig_len,
            },
        };

        if new_len > orig_len * 2 {
            result
                .warnings
                .push("File size doubled - review recommended".to_string());
            result.safe = false;
        }
        if new_lines.is_empty() && !orig_lines.is_empty() {
            result
                .warnings
                .push("All content removed - blocking change".to_string());
            result.safe = false;
        }

        for (pattern, name) in &self.important_patterns {
            let orig_count = pattern.find_iter(original_content).count();
            let new_count = pattern.find_iter(new_content).count();
            if orig_count > new_count {
                result
                    .warnings
                    .push(format!("Reduced {name} from {orig_count} to {new_count}"));
            }
        }

        result
    }

    pub fn should_skip_file(&self, file_path: &Path) -> bool {
        self.detector.is_generated(file_path)
    }

    pub fn get_approval_required(&self, risk_level: RiskLevel) -> bool {
        matches!(risk_level, RiskLevel::Medium | RiskLevel::High)
    }

    /// Port of `get_skipped_patterns` (the introspection surface).
    pub fn get_skipped_patterns(&self) -> Vec<(&'static str, Vec<&'static str>)> {
        vec![
            ("generated_patterns", GENERATED_PATTERNS.to_vec()),
            ("lock_files", LOCK_FILES.to_vec()),
            ("build_dirs", BUILD_DIRS.to_vec()),
            ("high_risk_patterns", HIGH_RISK_PATTERNS.to_vec()),
            ("medium_risk_patterns", MEDIUM_RISK_PATTERNS.to_vec()),
        ]
    }
}

