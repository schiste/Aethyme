//! Hand off one exact batch to processes that were already competing for a
//! merge verification slot. The queue state is advisory until normal exact
//! batch admission and gates succeed.

use std::collections::BTreeSet;
use std::io::{self, Write};
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

use serde::{Deserialize, Serialize};

use super::{BatchMember, BatchRequest, MAX_BATCH_MEMBERS};
use crate::file_lock::{ExclusiveFileLock, host_monotonic_ns};

const MAX_WAITERS: usize = 128;
const MAX_PATHS: usize = 128;
const MAX_PATH_BYTES: usize = 16 * 1024;
const MAX_STATE_BYTES: u64 = 4 * 1024 * 1024;
const CLAIM_DEADLINE: Duration = Duration::from_millis(50);
const FOLLOW_DEADLINE: Duration = Duration::from_secs(30 * 60);

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
struct Waiter {
    ticket: String,
    pid: i32,
    started: u64,
    ready_at: u128,
    coordinator: i64,
    base: String,
    member: BatchMember,
    paths: Vec<String>,
    bypass_cache: bool,
}

impl Waiter {
    fn alive(&self, directory: &Path) -> bool {
        // Ticket filenames are opaque, generated by tempfile; do not follow
        // a path supplied by a corrupt queue record.
        self.valid_ticket_name()
            && directory.join(&self.ticket).is_file()
            && crate::gates::process_start_time(self.pid) == Some(self.started)
    }

    fn valid_ticket_name(&self) -> bool {
        self.ticket.starts_with("live-")
            && self
                .ticket
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-')
    }
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Receipt {
    pub coordinator: i64,
    pub verifier: i64,
    pub base: String,
    pub members: Vec<BatchMember>,
    pub candidate: String,
    pub tree: String,
    pub gates: serde_json::Value,
}

#[derive(Serialize, Deserialize)]
struct Claim {
    leader: Waiter,
    members: Vec<Waiter>,
    // None while the leader holds the verification slot.
    result: Option<Completion>,
}

#[derive(Serialize, Deserialize)]
enum Completion {
    Verified(Receipt),
    Fallback,
}

#[derive(Default, Serialize, Deserialize)]
struct State {
    // Append order is admission order, even when processes share a clock tick.
    waiters: Vec<Waiter>,
    claims: Vec<Claim>,
}

pub(super) struct Ticket {
    directory: PathBuf,
    waiter: Waiter,
    marker: Option<tempfile::NamedTempFile>,
}

pub(super) enum Admission {
    Single,
    Leader(BatchRequest),
    Follower,
}

enum Handoff {
    Pending,
    Verified(Receipt),
    Fallback,
}

impl Ticket {
    pub(super) fn enqueue(
        main: &Path,
        coordinator: i64,
        member: BatchMember,
        base: &str,
        paths: &[String],
        bypass_cache: bool,
    ) -> Option<Self> {
        if paths.is_empty()
            || paths.len() > MAX_PATHS
            || paths.iter().map(String::len).sum::<usize>() > MAX_PATH_BYTES
        {
            return None;
        }
        let session_id = member.session_id;
        let pid = i32::try_from(std::process::id()).ok()?;
        let directory = main.join(".aethyme/run/submit-batch-waiters");
        std::fs::create_dir_all(&directory).ok()?;
        let marker = tempfile::Builder::new()
            .prefix("live-")
            .tempfile_in(&directory)
            .ok()?;
        let mut ticket = Self {
            directory,
            waiter: Waiter {
                ticket: marker.path().file_name()?.to_str()?.to_owned(),
                pid,
                started: crate::gates::process_start_time(pid)?,
                ready_at: 0,
                coordinator,
                base: base.into(),
                member,
                paths: paths.to_vec(),
                bypass_cache,
            },
            marker: Some(marker),
        };
        let ready_at = ticket
            .edit(|state| {
                state.reap(&ticket.directory);
                if state.waiters.len() >= MAX_WAITERS
                    || state.claims.len() >= MAX_WAITERS
                    || state
                        .waiters
                        .iter()
                        .any(|other| other.member.session_id == session_id)
                    || state
                        .claims
                        .iter()
                        .flat_map(|claim| &claim.members)
                        .any(|other| {
                            other.member.session_id == session_id && other.alive(&ticket.directory)
                        })
                {
                    return None;
                }
                let ready_at = host_monotonic_ns();
                if ready_at == 0 {
                    return None;
                }
                let mut waiter = ticket.waiter.clone();
                waiter.ready_at = ready_at;
                state.waiters.push(waiter);
                Some(ready_at)
            })
            .ok()??;
        ticket.waiter.ready_at = ready_at;
        Some(ticket)
    }

    /// Called after acquiring a real slot. Freeze the eligible requests that
    /// are already on disk, with no grace period for further arrivals.
    pub(super) fn admit(&self, ready_cutoff: u128) -> io::Result<Admission> {
        self.edit(|state| {
            state.reap(&self.directory);
            if state.claim_for(&self.waiter).is_some() {
                return Admission::Follower;
            }
            let compatible = |other: &&Waiter| {
                other.ready_at <= ready_cutoff
                    && other.coordinator == self.waiter.coordinator
                    && other.base == self.waiter.base
                    && other.bypass_cache == self.waiter.bypass_cache
            };
            let leader = state.waiters.iter().find(|other| **other == self.waiter);
            let coordinator = state
                .waiters
                .iter()
                .filter(compatible)
                .find(|other| other.member.session_id == self.waiter.coordinator);
            let members = match (leader, coordinator) {
                (Some(leader), Some(coordinator)) => {
                    select_members(leader, coordinator, state.waiters.iter().filter(compatible))
                }
                _ => Vec::new(),
            };
            if members.len() < 2 {
                state
                    .waiters
                    .retain(|other| other.ticket != self.waiter.ticket);
                return Admission::Single;
            }
            let request = BatchRequest {
                base: self.waiter.base.clone(),
                members: members.iter().map(|member| member.member.clone()).collect(),
            };
            state.waiters.retain(|other| !members.contains(other));
            state.claims.push(Claim {
                leader: self.waiter.clone(),
                members,
                result: None,
            });
            Admission::Leader(request)
        })
    }

    pub(super) fn complete(&self, receipt: Option<Receipt>) -> io::Result<Option<Receipt>> {
        self.edit(|state| {
            let claim = state
                .claims
                .iter_mut()
                .find(|claim| claim.leader == self.waiter && claim.result.is_none())?;
            let receipt = receipt.filter(|receipt| {
                claim
                    .members
                    .iter()
                    .all(|member| member.alive(&self.directory))
                    && receipt
                        .members
                        .iter()
                        .eq(claim.members.iter().map(|waiter| &waiter.member))
            });
            claim.result = Some(
                receipt
                    .clone()
                    .map_or(Completion::Fallback, Completion::Verified),
            );
            receipt
        })
    }

    pub(super) fn claim_is_live(&self) -> bool {
        self.read().is_ok_and(|state| {
            state.claim_for(&self.waiter).is_some_and(|claim| {
                claim.result.is_none()
                    && claim
                        .members
                        .iter()
                        .all(|member| member.alive(&self.directory))
            })
        })
    }

    /// Wait only for an accepted leader, with no slot held. Failures and
    /// crashed leaders send the original submit down its ordinary path once.
    pub(super) fn follow(&self) -> Option<Receipt> {
        let started = Instant::now();
        loop {
            if !self.waiter.alive(&self.directory) {
                return None;
            }
            let state = self.read().ok()?;
            let claim = state.claim_for(&self.waiter)?;
            let outcome = match &claim.result {
                Some(Completion::Verified(receipt)) => Handoff::Verified(receipt.clone()),
                Some(Completion::Fallback) => Handoff::Fallback,
                None if claim.leader.alive(&self.directory)
                    && claim
                        .members
                        .iter()
                        .all(|member| member.alive(&self.directory)) =>
                {
                    Handoff::Pending
                }
                None => Handoff::Fallback,
            };
            match outcome {
                Handoff::Verified(receipt) => return Some(receipt),
                Handoff::Fallback => return None,
                Handoff::Pending if started.elapsed() >= FOLLOW_DEADLINE => return None,
                Handoff::Pending => std::thread::sleep(Duration::from_millis(125)),
            }
        }
    }

    fn edit<T>(&self, edit: impl FnOnce(&mut State) -> T) -> io::Result<T> {
        let started = Instant::now();
        let lock_file = queue_file(&self.directory.join("lock"), true)?;
        let _lock = loop {
            if let Some(lock) = ExclusiveFileLock::try_acquire(lock_file.try_clone()?)? {
                break lock;
            }
            if started.elapsed() >= CLAIM_DEADLINE {
                return Err(io::Error::new(
                    io::ErrorKind::WouldBlock,
                    "submit batch queue is busy",
                ));
            }
            std::thread::sleep(Duration::from_millis(4));
        };
        let mut state = self.read()?;
        let result = edit(&mut state);
        let mut tmp = tempfile::NamedTempFile::new_in(&self.directory)?;
        serde_json::to_writer(&mut tmp, &state)?;
        tmp.flush()?;
        if tmp.as_file().metadata()?.len() > MAX_STATE_BYTES {
            return Err(io::Error::other("submit batch queue state is too large"));
        }
        tmp.persist(self.directory.join("state.json"))?;
        Ok(result)
    }

    fn read(&self) -> io::Result<State> {
        use std::io::Read;

        match queue_file(&self.directory.join("state.json"), false) {
            Ok(file) if file.metadata()?.len() <= MAX_STATE_BYTES => {
                Ok(serde_json::from_reader(file.take(MAX_STATE_BYTES + 1))?)
            }
            Ok(_) => Err(io::Error::other("submit batch queue state is too large")),
            Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(State::default()),
            Err(error) => Err(error),
        }
    }
}

impl Drop for Ticket {
    fn drop(&mut self) {
        // Withdraw independently of the metadata lock. A submit falling
        // back to individual work must stop being claimable immediately.
        drop(self.marker.take());
        let _ = self.edit(|state| {
            state
                .waiters
                .retain(|other| other.ticket != self.waiter.ticket);
            if let Some(claim) = state
                .claims
                .iter_mut()
                .find(|claim| claim.result.is_none() && claim.members.contains(&self.waiter))
            {
                claim.result = Some(Completion::Fallback);
            }
            // The receipt is kept until the other processes consume it.
            // Dropping a ticket in a still-live process must count as leaving.
            for claim in &mut state.claims {
                claim
                    .members
                    .retain(|other| other.ticket != self.waiter.ticket);
            }
            state.reap(&self.directory);
        });
    }
}

impl State {
    fn claim_for(&self, waiter: &Waiter) -> Option<&Claim> {
        self.claims
            .iter()
            .find(|claim| claim.members.contains(waiter))
    }

    fn reap(&mut self, directory: &Path) {
        let retain_live = |waiter: &Waiter| {
            if waiter.alive(directory) {
                return true;
            }
            if waiter.valid_ticket_name() {
                let _ = std::fs::remove_file(directory.join(&waiter.ticket));
            }
            false
        };
        self.waiters.retain(retain_live);
        for claim in &mut self.claims {
            let every_member_is_live = claim.members.iter().all(retain_live);
            if claim.result.is_none() && !every_member_is_live {
                claim.result = Some(Completion::Fallback);
            }
            claim.members.retain(retain_live);
        }
        self.claims.retain(|claim| !claim.members.is_empty());
    }
}

fn select_members<'a>(
    leader: &'a Waiter,
    coordinator: &'a Waiter,
    waiters: impl Iterator<Item = &'a Waiter>,
) -> Vec<Waiter> {
    let mut selected = BTreeSet::from([leader.ticket.as_str()]);
    let mut heads = BTreeSet::from([leader.member.head.as_str()]);
    let mut paths = leader
        .paths
        .iter()
        .map(String::as_str)
        .collect::<BTreeSet<_>>();
    if coordinator != leader {
        if !paths_are_disjoint(&paths, &coordinator.paths)
            || !heads.insert(&coordinator.member.head)
        {
            return Vec::new();
        }
        selected.insert(coordinator.ticket.as_str());
        paths.extend(coordinator.paths.iter().map(String::as_str));
    }
    let waiters = waiters.collect::<Vec<_>>();
    for other in &waiters {
        if selected.len() == MAX_BATCH_MEMBERS {
            break;
        }
        if !heads.contains(other.member.head.as_str()) && paths_are_disjoint(&paths, &other.paths) {
            selected.insert(other.ticket.as_str());
            heads.insert(other.member.head.as_str());
            paths.extend(other.paths.iter().map(String::as_str));
        }
    }
    waiters
        .into_iter()
        .filter(|waiter| selected.contains(waiter.ticket.as_str()))
        .cloned()
        .collect()
}

fn paths_are_disjoint(occupied: &BTreeSet<&str>, paths: &[String]) -> bool {
    paths.iter().all(|path| {
        // File/directory replacement is overlap even when the names differ.
        if occupied.contains(path.as_str())
            || path
                .match_indices('/')
                .any(|(offset, _)| occupied.contains(&path[..offset]))
        {
            return false;
        }
        let descendant = format!("{path}/");
        !occupied
            .range(descendant.as_str()..)
            .next()
            .is_some_and(|other| other.starts_with(&descendant))
    })
}

fn queue_file(path: &Path, create: bool) -> io::Result<std::fs::File> {
    let mut options = std::fs::OpenOptions::new();
    options.read(true).write(create).create(create);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt as _;
        options
            .custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK)
            .mode(0o600);
    }
    let file = options.open(path)?;
    if !file.metadata()?.is_file() {
        return Err(io::Error::other(
            "submit batch queue requires a regular file",
        ));
    }
    Ok(file)
}
