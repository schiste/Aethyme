//! The body `broker push --pr` gives the draft pull request it opens.
//!
//! A repository with a pull request template gets that template, filled from
//! what its commits already say: the `Problem`/`Decision`/`Rationale`
//! sections under the summary heading, `Validation` under the test heading,
//! and any `Contract decision:` line both ticked in the template's checkbox
//! and kept verbatim, because the contract check reads the PR body and not
//! the commits (a body without it fails CI, and a rerun replays the old
//! body). A repository without a template keeps the plain body.

/// Where GitHub looks for a single pull request template, compared
/// case-insensitively. The `PULL_REQUEST_TEMPLATE/` directory form is not
/// here: GitHub only applies those through a `?template=` query, never by
/// default, so there is no one template to pick.
const TEMPLATE_PATHS: [&str; 6] = [
    ".github/pull_request_template.md",
    "pull_request_template.md",
    "docs/pull_request_template.md",
    ".github/pull_request_template.txt",
    "pull_request_template.txt",
    "docs/pull_request_template.txt",
];

/// Commit-message trailers that are bookkeeping, not prose: they never belong
/// in a summary section even when Git folds them into the last one.
const TRAILER_PREFIXES: [&str; 6] = [
    "co-authored-by:",
    "signed-off-by:",
    "reviewed-by:",
    "claude-session:",
    "contract decision:",
    "contract justification:",
];

/// One commit as the body builder needs it, oldest first.
pub(crate) struct BodyCommit<'a> {
    pub sha: &'a str,
    pub subject: &'a str,
    pub message: &'a str,
}

/// The repository's single default pull request template among `paths`
/// (tracked paths at the base commit), if it has one.
pub(crate) fn template_path(paths: &[String]) -> Option<&str> {
    TEMPLATE_PATHS.iter().find_map(|wanted| {
        paths
            .iter()
            .find(|path| path.eq_ignore_ascii_case(wanted))
            .map(String::as_str)
    })
}

/// Whether a workflow file skips draft pull requests: it gates on
/// `github.event.pull_request.draft`. A text match is enough here; the answer
/// only decides whether `push --pr` adds a one-line note.
pub(crate) fn workflow_skips_drafts(workflow: &str) -> bool {
    workflow.contains("pull_request.draft")
}

/// A conservative UTF-8 byte cap below GitHub's reported 65,536-character limit.
const MAX_GENERATED_BODY_BYTES: usize = 65_536;
const BODY_TRUNCATION_NOTICE: &str =
    "[Generated PR details were omitted to stay within the 65,536-byte safety cap.]";
const BODY_FIELD_TRUNCATION_SUFFIX: &str = "\n[truncated to fit the 65,536-byte safety cap]";

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum ComposeError {
    RequiredContentExceedsLimit { minimum_bytes: usize },
}

impl std::fmt::Display for ComposeError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::RequiredContentExceedsLimit { minimum_bytes } => write!(
                formatter,
                "the generated pull-request body needs at least {minimum_bytes} UTF-8 bytes to preserve the repository template and contract content; the conservative generated-body cap is {MAX_GENERATED_BODY_BYTES} bytes"
            ),
        }
    }
}

/// The draft PR body generated by `broker push --pr`. Explicit, caller-provided
/// GitHub operation arguments do not pass through this bounded composer.
pub(crate) fn compose(
    task: Option<&str>,
    commits: &[BodyCommit<'_>],
    template: Option<&str>,
) -> Result<String, ComposeError> {
    let contract_lines = contract_lines(commits);
    let (summary, validation) = if template.is_some() {
        commit_prose(task, commits)
    } else {
        (
            task.map(str::trim).unwrap_or_default().to_owned(),
            String::new(),
        )
    };
    let summary_present = if template.is_some() {
        !summary.is_empty()
    } else {
        task.is_some()
    };
    let commit_lines = commit_lines(commits);
    let full_commit_list = commit_lines.concat();
    let full = render_body(
        template,
        &summary,
        summary_present,
        &validation,
        &contract_lines,
        &full_commit_list,
        false,
    );
    if full.len() <= MAX_GENERATED_BODY_BYTES {
        return Ok(full);
    }

    // The template, declared contract decisions, required headings and footer
    // stay intact. Only generated task/commit prose and the repeated commit
    // list are shortened. The notice makes that loss visible in the draft.
    let (minimum_summary, summary_omitted) = truncate_body_field(&summary, 0, "summary");
    let (minimum_validation, validation_omitted) =
        truncate_body_field(&validation, 0, "validation");
    let (minimum_commit_list, commits_omitted) = bounded_commit_list(&commit_lines, 0);
    let minimum_omitted = summary_omitted || validation_omitted || commits_omitted;
    let minimum = render_body(
        template,
        &minimum_summary,
        summary_present,
        &minimum_validation,
        &contract_lines,
        &minimum_commit_list,
        minimum_omitted,
    );
    if minimum.len() > MAX_GENERATED_BODY_BYTES {
        return Err(ComposeError::RequiredContentExceedsLimit {
            minimum_bytes: minimum.len(),
        });
    }

    // Increase the per-section budget while checking the exact final body.
    // Measuring the rendered UTF-8 string accounts for template placement
    // and all headings without relying on estimates.
    let mut best = minimum;
    let mut low = 1;
    let mut high = MAX_GENERATED_BODY_BYTES;
    while low <= high {
        let budget = low + (high - low) / 2;
        let (candidate_summary, summary_omitted) = truncate_body_field(&summary, budget, "summary");
        let (candidate_validation, validation_omitted) =
            truncate_body_field(&validation, budget, "validation");
        let (candidate_commit_list, commits_omitted) = bounded_commit_list(&commit_lines, budget);
        let candidate_omitted = summary_omitted || validation_omitted || commits_omitted;
        let candidate = render_body(
            template,
            &candidate_summary,
            summary_present,
            &candidate_validation,
            &contract_lines,
            &candidate_commit_list,
            candidate_omitted,
        );
        if candidate.len() <= MAX_GENERATED_BODY_BYTES {
            best = candidate;
            low = budget + 1;
        } else {
            high = budget - 1;
        }
    }
    Ok(best)
}

fn truncate_body_field(text: &str, byte_limit: usize, label: &str) -> (String, bool) {
    if text.len() <= byte_limit {
        return (text.to_owned(), false);
    }
    if byte_limit < BODY_FIELD_TRUNCATION_SUFFIX.len() {
        return (format!("[{label} omitted]"), true);
    }
    let prefix_limit = byte_limit - BODY_FIELD_TRUNCATION_SUFFIX.len();
    let mut prefix_end = prefix_limit.min(text.len());
    while !text.is_char_boundary(prefix_end) {
        prefix_end -= 1;
    }
    let mut bounded = String::with_capacity(prefix_end + BODY_FIELD_TRUNCATION_SUFFIX.len());
    bounded.push_str(&text[..prefix_end]);
    bounded.push_str(BODY_FIELD_TRUNCATION_SUFFIX);
    (bounded, true)
}

fn commit_lines(commits: &[BodyCommit<'_>]) -> Vec<String> {
    commits
        .iter()
        .rev()
        .map(|commit| {
            format!(
                "- {} {}\n",
                &commit.sha[..commit.sha.len().min(10)],
                commit.subject
            )
        })
        .collect()
}

fn bounded_commit_list(lines: &[String], byte_limit: usize) -> (String, bool) {
    let total_bytes = lines
        .iter()
        .fold(0usize, |total, line| total.saturating_add(line.len()));
    if total_bytes <= byte_limit {
        return (lines.concat(), false);
    }

    let reserve_marker = format!(
        "- {} commits omitted to fit the body size limit.\n",
        lines.len()
    );
    let mut output = String::new();
    for (index, line) in lines.iter().enumerate() {
        let omitted = lines.len() - index;
        let marker = format!("- {omitted} commits omitted to fit the body size limit.\n");
        if output
            .len()
            .saturating_add(line.len())
            .saturating_add(reserve_marker.len())
            <= byte_limit
        {
            output.push_str(line);
        } else {
            if output.len().saturating_add(marker.len()) <= byte_limit {
                output.push_str(&marker);
            }
            return (output, true);
        }
    }
    (output, false)
}

fn render_body(
    template: Option<&str>,
    summary: &str,
    summary_present: bool,
    validation: &str,
    contract_lines: &[String],
    commit_list: &str,
    details_omitted: bool,
) -> String {
    let mut body = match template {
        Some(template) => fill_template(template, summary, validation, contract_lines),
        None => {
            let mut body = String::new();
            if summary_present {
                body.push_str(summary.trim());
                body.push_str("\n\n");
            }
            if !contract_lines.is_empty() {
                body.push_str(&contract_lines.join("\n"));
                body.push_str("\n\n");
            }
            body
        }
    };
    body.push_str("Commits:\n");
    body.push_str(commit_list);
    if details_omitted {
        body.push('\n');
        body.push_str(BODY_TRUNCATION_NOTICE);
        body.push('\n');
    }
    body.push_str("\nOpened by aethyme broker push as a draft.\n");
    body
}

/// `Contract decision:` and `Contract justification:` lines from every
/// commit, verbatim and de-duplicated, in commit order.
fn contract_lines(commits: &[BodyCommit<'_>]) -> Vec<String> {
    let mut lines: Vec<String> = Vec::new();
    for commit in commits {
        for line in commit.message.lines() {
            let line = line.trim();
            let lower = line.to_ascii_lowercase();
            if (lower.starts_with("contract decision:")
                || lower.starts_with("contract justification:"))
                && !lines.iter().any(|seen| seen == line)
            {
                lines.push(line.to_string());
            }
        }
    }
    lines
}

fn without_trailers(text: &str) -> String {
    text.lines()
        .filter(|line| {
            let lower = line.trim().to_ascii_lowercase();
            !TRAILER_PREFIXES
                .iter()
                .any(|prefix| lower.starts_with(prefix))
        })
        .collect::<Vec<_>>()
        .join("\n")
        .trim()
        .to_string()
}

/// The summary prose and the validation prose the commits carry.
fn commit_prose(task: Option<&str>, commits: &[BodyCommit<'_>]) -> (String, String) {
    let mut summary: Vec<String> = Vec::new();
    let mut validation: Vec<String> = Vec::new();
    if let Some(task) = task.map(str::trim).filter(|task| !task.is_empty()) {
        summary.push(task.to_string());
    }
    let several = commits.len() > 1;
    for commit in commits {
        let sections = aethyme_enhance::hygiene::commit_message_sections(commit.message);
        let mut parts: Vec<String> = Vec::new();
        for (name, text) in &sections {
            let text = without_trailers(text);
            if text.is_empty() {
                continue;
            }
            if name == "Validation" {
                validation.push(if several {
                    format!("{}: {text}", commit.subject)
                } else {
                    text
                });
            } else if matches!(name.as_str(), "Problem" | "Decision" | "Rationale") {
                parts.push(format!("**{name}:** {text}"));
            }
        }
        if parts.is_empty() {
            // A sectionless commit still names what it did, unless it is the
            // only commit and the task already says so.
            if several || summary.is_empty() {
                summary.push(format!("- {}", commit.subject));
            }
        } else if several {
            summary.push(format!("**{}**\n\n{}", commit.subject, parts.join("\n\n")));
        } else {
            summary.push(parts.join("\n\n"));
        }
    }
    (summary.join("\n\n"), validation.join("\n\n"))
}

#[derive(Clone, Copy, PartialEq)]
enum Slot {
    Summary,
    Validation,
    Contract,
}

fn heading_slot(line: &str) -> Option<Slot> {
    let text = line.trim_start().strip_prefix('#')?;
    let text = text.trim_start_matches('#').trim().to_ascii_lowercase();
    if text.contains("contract") {
        Some(Slot::Contract)
    } else if [
        "summary",
        "description",
        "overview",
        "what",
        "why",
        "changes",
    ]
    .iter()
    .any(|word| text.contains(word))
    {
        Some(Slot::Summary)
    } else if ["test", "validation", "verification"]
        .iter()
        .any(|word| text.contains(word))
    {
        Some(Slot::Validation)
    } else {
        None
    }
}

/// Tick the template's `- [ ] **<label>**` checkbox for each declared
/// contract decision, so a template-driven contract check sees it the same
/// way the verbatim line already says it.
fn tick_contract_boxes(template: &str, contract_lines: &[String]) -> String {
    let labels: Vec<String> = contract_lines
        .iter()
        .filter_map(|line| {
            let rest = line.get("contract decision:".len()..)?;
            line.to_ascii_lowercase()
                .starts_with("contract decision:")
                .then(|| {
                    rest.trim()
                        .split(|c: char| !(c.is_ascii_alphabetic() || c == '-'))
                        .next()
                        .unwrap_or_default()
                        .to_ascii_lowercase()
                })
        })
        .filter(|label| !label.is_empty())
        .collect();
    template
        .lines()
        .map(|line| {
            let trimmed = line.trim_start();
            let ticked = labels.iter().any(|label| {
                trimmed
                    .to_ascii_lowercase()
                    .starts_with(&format!("- [ ] **{label}**"))
            });
            if ticked {
                line.replacen("- [ ]", "- [x]", 1)
            } else {
                line.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn fill_template(
    template: &str,
    summary: &str,
    validation: &str,
    contract_lines: &[String],
) -> String {
    let template = tick_contract_boxes(template, contract_lines);
    let contract = contract_lines.join("\n");
    let lines: Vec<&str> = template.lines().collect();
    let mut out: Vec<String> = Vec::new();
    let mut placed = [false; 3];
    let mut index = 0;
    while index < lines.len() {
        out.push(lines[index].to_string());
        let slot = heading_slot(lines[index]);
        index += 1;
        let Some(slot) = slot else { continue };
        let (text, done) = match slot {
            Slot::Summary => (summary, &mut placed[0]),
            Slot::Validation => (validation, &mut placed[1]),
            Slot::Contract => (contract.as_str(), &mut placed[2]),
        };
        if *done || text.is_empty() {
            continue;
        }
        // Past the blank lines and the guidance comment that follow the
        // heading, so the filled text reads after the instructions.
        while index < lines.len() && lines[index].trim().is_empty() {
            out.push(lines[index].to_string());
            index += 1;
        }
        if index < lines.len() && lines[index].trim_start().starts_with("<!--") {
            while index < lines.len() {
                let closes = lines[index].contains("-->");
                out.push(lines[index].to_string());
                index += 1;
                if closes {
                    break;
                }
            }
            out.push(String::new());
        }
        out.push(text.to_owned());
        out.push(String::new());
        *done = true;
    }
    let mut body = out.join("\n").trim_end().to_string();
    body.push_str("\n\n");
    // Text with no heading to sit under still reaches the reader, and the
    // contract line still reaches the check.
    let mut prefix = String::new();
    if !placed[0] && !summary.is_empty() {
        prefix.push_str(summary);
        prefix.push_str("\n\n");
    }
    if !placed[1] && !validation.is_empty() {
        body.push_str(&format!("Validation: {validation}\n\n"));
    }
    if !placed[2] && !contract.is_empty() {
        body.push_str(&contract);
        body.push_str("\n\n");
    }
    format!("{prefix}{body}")
}

#[cfg(test)]
mod tests {
    use super::*;

    const SHA: &str = "0123456789abcdef0123456789abcdef01234567";

    fn commit<'a>(subject: &'a str, message: &'a str) -> BodyCommit<'a> {
        BodyCommit {
            sha: SHA,
            subject,
            message,
        }
    }

    const MESSAGE: &str = "fix(broker): keep the sweep off the hot path\n\n\
        Problem: every command paid for a full sweep.\n\n\
        Decision: bound it to 250 ms.\n\n\
        Rationale: the sweep is advisory.\n\n\
        Validation: cargo test -p aethyme-broker gc passes.\n\n\
        Contract decision: none\n\
        Co-Authored-By: Someone <someone@example.com>\n";

    const TEMPLATE: &str = "<!-- top comment -->\n\n## Summary\n\n<!-- 1-3 sentences -->\n\n\
        ## Contract\n\n<!-- pick one -->\n\n- [ ] **none** — internal change.\n\
        - [ ] **introduce** — adds a new entry point.\n\n## Test plan\n\n- [ ] `cargo test`\n";

    #[test]
    fn without_a_template_the_body_is_unchanged_but_for_the_contract_line() {
        let plain = "fix(x): y\n\nJust a body.\n";
        let body = compose(Some("Do the thing"), &[commit("fix(x): y", plain)], None).unwrap();
        assert_eq!(
            body,
            "Do the thing\n\nCommits:\n- 0123456789 fix(x): y\n\nOpened by aethyme broker push as a draft.\n"
        );
        let body = compose(Some("Do the thing"), &[commit("fix(x): y", MESSAGE)], None).unwrap();
        assert!(body.contains("\nContract decision: none\n"), "{body}");
    }

    #[test]
    fn a_template_is_filled_from_the_commit_sections() {
        let body = compose(
            None,
            &[commit(
                "fix(broker): keep the sweep off the hot path",
                MESSAGE,
            )],
            Some(TEMPLATE),
        )
        .unwrap();
        let summary = body.find("## Summary").unwrap();
        let problem = body
            .find("**Problem:** every command paid for a full sweep.")
            .expect(&body);
        let contract = body.find("## Contract").unwrap();
        assert!(summary < problem && problem < contract, "{body}");
        assert!(
            body.find("<!-- 1-3 sentences -->").unwrap() < problem,
            "{body}"
        );
        let test_plan = body.find("## Test plan").unwrap();
        assert!(
            body[test_plan..].contains("cargo test -p aethyme-broker gc passes."),
            "{body}"
        );
        assert!(
            !body.contains("Co-Authored-By"),
            "trailers stay out of the prose: {body}"
        );
        assert!(
            body.ends_with("Opened by aethyme broker push as a draft.\n"),
            "{body}"
        );
    }

    #[test]
    fn the_contract_decision_reaches_the_contract_check() {
        let body = compose(None, &[commit("fix(broker): s", MESSAGE)], Some(TEMPLATE)).unwrap();
        assert!(body.contains("- [x] **none** — internal change."), "{body}");
        assert!(body.contains("- [ ] **introduce**"), "{body}");
        assert_eq!(
            crate::contract_check::parse_contract_decision(&body),
            Some(crate::contract_check::Decision::None)
        );
        let bare = compose(
            None,
            &[commit("fix(broker): s", MESSAGE)],
            Some("Describe the change.\n"),
        )
        .unwrap();
        assert_eq!(
            crate::contract_check::parse_contract_decision(&bare),
            Some(crate::contract_check::Decision::None),
            "a template without a contract heading still carries the line: {bare}"
        );
    }

    #[test]
    fn unicode_is_bounded_by_utf8_bytes_without_splitting_code_points() {
        let task = "🧪".repeat(20_000);
        let body = compose(Some(&task), &[], None).unwrap();

        assert!(body.len() <= MAX_GENERATED_BODY_BYTES);
        assert!(body.len() < task.len());
        assert!(body.starts_with("🧪"));
        assert!(body.contains(BODY_TRUNCATION_NOTICE));
    }

    #[test]
    fn a_large_unicode_history_is_bounded_and_keeps_required_sections() {
        let subjects: Vec<String> = (0..2_000)
            .map(|index| format!("fix: storage entry {index} 🧭"))
            .collect();
        let messages: Vec<String> = (0..2_000)
            .map(|index| {
                format!(
                    "Problem: cache entry {index} is not retained.\n\nValidation: cargo test fixture {index} passes.\n\nContract decision: none"
                )
            })
            .collect();
        let commits: Vec<BodyCommit<'_>> = subjects
            .iter()
            .zip(&messages)
            .map(|(subject, message)| BodyCommit {
                sha: SHA,
                subject,
                message,
            })
            .collect();

        let body = compose(
            Some("Keep the contract decision visible 🧭"),
            &commits,
            Some(TEMPLATE),
        )
        .expect("ordinary required sections fit");

        assert!(
            body.len() <= MAX_GENERATED_BODY_BYTES,
            "{} bytes",
            body.len()
        );
        assert!(body.contains("## Summary"), "{body}");
        assert!(
            body.contains("Keep the contract decision visible 🧭"),
            "the original task summary was lost: {body}"
        );
        assert!(body.contains("## Contract"), "{body}");
        assert!(body.contains("## Test plan"), "{body}");
        assert!(body.contains("Contract decision: none"), "{body}");
        assert!(body.contains("- [x] **none**"), "{body}");
        assert!(
            body.contains("🧭"),
            "Unicode commit text was not retained: {body}"
        );
        assert!(
            body.contains("commits omitted to fit the body size limit"),
            "{body}"
        );
        assert!(body.contains(BODY_TRUNCATION_NOTICE), "{body}");
        assert!(body.ends_with("Opened by aethyme broker push as a draft.\n"));
    }

    #[test]
    fn an_oversized_unicode_message_is_truncated_on_a_utf8_boundary() {
        let repeated = "🧪".repeat(MAX_GENERATED_BODY_BYTES);
        let message =
            format!("Problem: {repeated}\n\nValidation: {repeated}\n\nContract decision: none");
        let body = compose(
            Some(&format!("Review {repeated}")),
            &[commit("fix: large Unicode input", &message)],
            Some(TEMPLATE),
        )
        .expect("required template and contract fit");

        assert!(
            body.len() <= MAX_GENERATED_BODY_BYTES,
            "{} bytes",
            body.len()
        );
        assert!(
            body.contains("Review 🧪"),
            "original Unicode summary prose was not retained: {body}"
        );
        assert!(
            !body.contains('\u{fffd}'),
            "UTF-8 text was corrupted: {body}"
        );
        assert!(body.contains("Contract decision: none"), "{body}");
        assert!(body.contains("[truncated to fit the 65,536-byte safety cap]"));
        assert!(body.ends_with("Opened by aethyme broker push as a draft.\n"));
    }

    #[test]
    fn a_template_that_cannot_fit_with_contract_content_is_refused() {
        let template = format!("## Summary\n{}\n", "template text\n".repeat(5_000));
        let result = compose(
            Some("keep this summary"),
            &[commit("fix: contract", MESSAGE)],
            Some(&template),
        );
        assert!(matches!(
            result,
            Err(ComposeError::RequiredContentExceedsLimit { .. })
        ));
    }

    #[test]
    fn the_default_template_is_found_case_insensitively() {
        let paths = vec![
            "README.md".to_string(),
            ".github/PULL_REQUEST_TEMPLATE.md".to_string(),
            "docs/pull_request_template.md".to_string(),
        ];
        assert_eq!(
            template_path(&paths),
            Some(".github/PULL_REQUEST_TEMPLATE.md")
        );
        assert_eq!(template_path(&["src/lib.rs".to_string()]), None);
        assert_eq!(
            template_path(&[".github/PULL_REQUEST_TEMPLATE/bug.md".to_string()]),
            None,
            "a template directory has no default template"
        );
    }

    #[test]
    fn draft_skipping_workflows_are_recognised() {
        assert!(workflow_skips_drafts(
            "jobs:\n  build:\n    if: github.event.pull_request.draft == false\n"
        ));
        assert!(!workflow_skips_drafts("on: [push, pull_request]\n"));
    }
}
