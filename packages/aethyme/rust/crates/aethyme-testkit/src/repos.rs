/// The pnpm/TypeScript demo repo the enhance and skills suites deploy
/// into (the pytest `_build_repo` helper, shared by four files).
pub fn build_pnpm_demo_repo(root: &Path) -> PathBuf {
    write(
        root.join("package.json"),
        "{\"name\":\"demo\",\"scripts\":{\"test\":\"vitest\",\"dev\":\"vite\",\"build\":\"vite build\"}}\n",
    );
    write(root.join("pnpm-lock.yaml"), "lockfileVersion: '9.0'\n");
    write(root.join("src/main.ts"), "console.log('demo')\n");
    root.to_path_buf()
}

/// A repo with one fixable item per autofix fixer plus protected paths
/// the safety engine must refuse to patch.
pub fn build_fixable_repo(tmp: &Path) -> PathBuf {
    let repo = tmp.join("autofix-repo");
    write(repo.join("src/module.py"), "\"\"\"Module purpose.\"\"\"\n\nx = 1\n");
    write(repo.join("docs/page.md"), "[Absolute](/src/module.py)\n");
    write(
        repo.join("ui/Panel.tsx"),
        "import React from 'react';\nexport function Panel() { return <button>Save Changes</button>; }\n",
    );
    write(repo.join("package.json"), "{}\n");
    write(repo.join("Cargo.lock"), "# lock\n");
    write(repo.join("node_modules/pkg/index.js"), "module.exports = 1;\n");
    repo
}

