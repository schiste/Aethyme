//! Programmatic fixture repositories.
//!
//! Successor to `tests/support/repo_builders.py` plus the per-suite
//! builders the pytest files defined inline. Fixtures are BUILT, never
//! checked in — CONTRIBUTING's fixture rule — so the bytes a suite
//! asserts against are visible in one place next to the assertions.
//!
//! `build_indexable_core_repo` and `build_medium_fixture_repo` from the
//! Python module are deliberately absent: their only consumer was the
//! migration parity harness (`scripts/migration/`), removed in
//! python-retirement Phase 6. Porting builders with no caller would
//! carry dead scaffolding into the Rust tree.

use std::path::{Path, PathBuf};

/// Write `content` to `path`, creating parent directories.
pub fn write(path: impl AsRef<Path>, content: &str) {
    let path = path.as_ref();
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .unwrap_or_else(|error| panic!("mkdir {}: {error}", parent.display()));
    }
    std::fs::write(path, content)
        .unwrap_or_else(|error| panic!("write {}: {error}", path.display()));
}

/// Read a UTF-8 file, panicking with the path on failure.
pub fn read(path: impl AsRef<Path>) -> String {
    let path = path.as_ref();
    std::fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("read {}: {error}", path.display()))
}

