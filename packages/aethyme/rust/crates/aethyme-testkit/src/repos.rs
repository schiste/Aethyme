/// The two-module Python repo the graph/task navigation suite indexes.
/// Call [`bootstrap_repo_fragments`] afterwards to materialize the graph.
pub fn build_demo_source_repo(root: &Path) -> PathBuf {
    write(root.join("README.md"), "# Demo Repo\n\nSmall test repo.\n");
    write(
        root.join("src/main.py"),
        "from src.auth import validate_token\n\ndef main():\n    return validate_token()\n",
    );
    write(root.join("src/auth.py"), "def validate_token():\n    return True\n");
    root.to_path_buf()
}

/// Write graph fragments and materialize the redb store for `root`.
///
/// Graph queries read from the redb store and will not create it
/// themselves, so fixture repos must run the same two steps
/// `scripts/eval/setup-playground.sh` runs.
pub fn bootstrap_repo_fragments(root: &Path) {
    let fragments = std::process::Command::new(crate::bins::graph_index_bin())
        .args([
            "--repo-root",
            &root.to_string_lossy(),
            "--repo-name",
            "demo-repo",
            "--engine-version",
            "local-test",
            "--json",
        ])
        .output()
        .expect("spawn aethyme-graph-index");
    assert!(
        fragments.status.success(),
        "aethyme-graph-index failed: {}",
        String::from_utf8_lossy(&fragments.stderr)
    );

    let indexed = std::process::Command::new(crate::bins::engine_bin())
        .args(["index", "--repo", &root.to_string_lossy(), "--from-fragments"])
        .output()
        .expect("spawn aethyme-engine-cli index");
    assert!(
        indexed.status.success(),
        "engine index failed: {}",
        String::from_utf8_lossy(&indexed.stderr)
    );
}
